FROM RAW.EXPORT_TRANSACTIONS f
JOIN RAW.THAI_EXPORT_CONTEXT e ON e.ID = f.ENTITY_ID
CROSS JOIN thresh
GROUP BY e.ID, e.NAME, e.REGION, e.CATEGORY, e.STATUS;

